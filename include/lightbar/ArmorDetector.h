#pragma once
// ============================================================================
//  ArmorDetector.h  ——  "灯条检测器"这个类的说明书
// ----------------------------------------------------------------------------
//  为什么要用 class（类）而不是一堆散装函数？
//
//  因为检测这件事有"状态"：
//    这一帧用的 mask 是什么、检出了哪些候选灯条、参数是什么……
//    如果写成散装函数，这些数据要么靠全局变量（很危险），要么一层层传参（很啰嗦）。
//    用类，就可以把"数据"（成员变量）和"操作数据的函数"（成员函数）装在一起。
//
//  这个头文件里只有"声明"（函数长什么样），真正的"实现"在 ArmorDetector.cpp。
//  这就像餐厅的菜单：菜单上写菜名和价格，厨房里才是做法。
// ============================================================================

#include <opencv2/opencv.hpp>
#include <vector>

#include "lightbar/Config.h"
#include "lightbar/Types.h"

namespace lb
{

class ArmorDetector
{
public:
    // ------------------------------------------------------------------
    //  构造函数：创建对象时自动调用一次，用来"初始化"。
    //  explicit 的作用：禁止 `ArmorDetector d = config;` 这种隐式转换，
    //  避免一些难查的 bug。新手记住"单参数构造函数加 explicit"就行。
    //
    //  `const Config& config = Config()` 的意思是：
    //    - 传进来一个 Config，用 & 表示"引用"（不复制，效率高）
    //    - const 表示"我保证不修改你的 config"
    //    - = Config() 表示"如果你不传，就用一个默认的"
    // ------------------------------------------------------------------
    explicit ArmorDetector(const Config& config = Config());

    // ------------------------------------------------------------------
    //  核心函数：检测一帧图像里的装甲板
    //    bgrImage ：输入图像（OpenCV 默认是 BGR 三通道彩色图）
    //    plate    ：输出参数。找到就把结果填进去；没找到就保持 found = false
    //  返回值：true 表示找到了，false 表示没找到
    //
    //  注意参数里的 & ：这叫"引用传递"。函数里对 plate 的修改会直接影响
    //  调用者的变量，不需要 return 一个结果再赋值。这是 C++ 里最常用的
    //  "通过参数把结果带出来"的写法。
    // ------------------------------------------------------------------
    bool detect(const cv::Mat& bgrImage, ArmorPlate& plate);

    // ------------------------------------------------------------------
    //  把检测结果画到图像上（会直接修改 image）
    //    - 所有候选灯条：画黄色线段 + 端点
    //    - 最终选中的装甲板：画绿色四边形 + 中心点 + 文字
    // ------------------------------------------------------------------
    void draw(cv::Mat& image, const ArmorPlate& plate) const;

    // ------------------------------------------------------------------
    //  调试用：把最近一次的 mask（二值图）单独显示出来。
    //  调参时这是你最重要的窗口 —— 它能告诉你"二值化到底筛出了什么"。
    // ------------------------------------------------------------------
    void showMask() const;

    // 取最近一次的候选灯条列表（调试/统计用）
    const std::vector<LightBar>& candidates() const { return bars_; }

private:
    // ------------------------------------------------------------------
    //  下面这些是"内部实现细节"，外部不需要知道，所以放 private。
    //  这是好架构的一条基本原则：对外只暴露必要的接口。
    // ------------------------------------------------------------------

    // 第一步：彩色图 → 二值 mask
    cv::Mat buildMask(const cv::Mat& bgrImage) const;

    // 第二、三步：在 mask 上找轮廓，筛出所有候选灯条
    std::vector<LightBar> findLightBars(const cv::Mat& mask) const;

    // 判断"一个旋转矩形"够不够格当灯条；够格就顺便把端点算好填进 bar
    bool isLightBar(const cv::RotatedRect& rect, LightBar& bar) const;

    // 试着把两根灯条配成一块装甲板；成功返回 true
    bool tryMakePlate(const LightBar& a, const LightBar& b, ArmorPlate& plate) const;

    // 给一对灯条打分，分数越低越像同一块装甲板（用于在多个候选对里选最优）
    float pairScore(const LightBar& a, const LightBar& b) const;

    // ------------------------------------------------------------------
    //  成员变量：每个 ArmorDetector 对象自己的一份数据
    // ------------------------------------------------------------------
    Config cfg_;                    // 参数副本（构造时拷贝一份，之后独立）
    cv::Mat mask_;                  // 最近一次的 mask（二值图）
    std::vector<LightBar> bars_;    // 最近一次的所有候选灯条
};

}   // namespace lb