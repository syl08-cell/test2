#pragma once
// ============================================================================
//  Config.h  ——  所有"可以调的数字"都集中放在这个文件里
// ----------------------------------------------------------------------------
//  为什么要把参数集中？
//    新手最常见的困境是：程序能跑，但效果不对，却不知道该改哪里。
//    如果阈值、面积范围这些数字散落在三个 .cpp 文件里，你就要满项目找。
//    把它们全部放进一个 struct，你调参时只需要打开这一个文件。
//
//  这个文件不需要 #include 任何东西 —— 它只有普通数字和枚举。
// ============================================================================

namespace lb   // lb = light bar，我们给"自己的代码"起一个命名空间，避免和别人的重名
{

// ----------------------------------------------------------------------------
//  敌方颜色。比赛里灯条只有两种颜色：红 or 蓝。
//  enum class 是"枚举类"，你可以把它理解成"只能取这几个值的一种新类型"。
//  写 EnemyColor::Red 比写数字 0 更清楚，写错了编译器还会报错。
// ----------------------------------------------------------------------------
enum class EnemyColor
{
    Red,    // 红方：灯条偏红/橙
    Blue    // 蓝方：灯条偏蓝/青
};

// ----------------------------------------------------------------------------
//  Config：所有参数的集合
//
//  用法：在 main.cpp 里写
//        lb::Config config;            // 全部用默认值
//        config.vMin = 40;             // 只改其中一项（比如亮度阈值）
//        lb::ArmorDetector detector(config);
//
//  每一项后面都写了"调大会怎样、调小会怎样"，调参时照着看。
// ----------------------------------------------------------------------------
struct Config
{
    // ======================== 一、颜色阈值（第一步二值化用） ========================
    //
    //  OpenCV 的 HSV 取值范围很反直觉，务必记住：
    //    H（色相）  0 ~ 179      （不是 0~360！OpenCV 把角度除以 2 了）
    //    S（饱和度）0 ~ 255      （越大颜色越"浓"，越接近灰色）
    //    V（亮度）  0 ~ 255      （越大越亮）
    //
    //  红色在色相环上正好跨过 0 点，所以要用"两段"来框：
    //      第一段：H 从 0   到 hRedLowMax
    //      第二段：H 从 hRedHighMin 到 179
    //  两段的结果用"或"合起来，才是完整的红色。
    // ------------------------------------------------------------------------------

    EnemyColor enemyColor = EnemyColor::Red;   // 当前识别哪种颜色

    int hRedLowMax  = 15;    // 红色低段上限。调大 → 橙色、黄色也会被当成红色
    int hRedHighMin = 165;   // 红色高段下限。调小 → 偏紫的颜色也会进来
    int hBlueMin    = 80;    // 蓝色段下限（备用，enemyColor = Blue 时生效）
    int hBlueMax    = 130;   // 蓝色段上限

    int sMin = 90;   // 饱和度下限。调大 → 只保留"颜色很浓"的像素（更干净，但暗处灯条会漏）
                     // 调小 → 灰白色的数字、墙面也会进来（干扰变多）
                     // 本视频实测：灯条像素 S ≥ 150，背景 S 很低，所以 90 很安全

    int vMin = 60;   // 亮度下限。调大 → 只保留很亮的（能排除地面倒影，但远处小灯条会漏）
                     // 调小 → 倒影、反光也会进来（这时就靠后面的"配对规则"排除）
                     // 本视频很暗，灯条 V 约 82~255；这里取 60 留一点余量

    // ======================== 二、形态学（去噪，默认关掉） ========================
    //
    //  常见做法是"开运算"（先腐蚀再膨胀）去掉小噪点。但对这个视频要小心：
    //  实测有些灯条只有 3 像素宽，3x3 的腐蚀会把它整根吃掉，灯条直接消失。
    //  所以这里默认不用；如果你的视频噪点多、灯条又够粗，可以改成 true。
    // ------------------------------------------------------------------------------
    bool useDilate = false;   // 只做膨胀（让灯条变粗一点、连上断点），不腐蚀
    int  dilateSize = 3;      // 膨胀核大小，必须是正奇数（3、5、7...）

    // ======================== 三、灯条本身的几何筛选 ========================
    //
    //  minAreaRect 包出来的矩形有两个边长：长边 length、短边 width。
    //  灯条的典型特征：又细又长 + 基本竖直。
    //  本视频实测（真实数据，不是猜的）：
    //      长边 15 ~ 52 像素，短边 3 ~ 10 像素，长宽比 3.2 ~ 6.2
    //  所以下面的范围取的是"比实测更宽一点"的值，给不同距离留余量。
    // ------------------------------------------------------------------------------

    double minArea = 15.0;    // 轮廓面积下限（像素²）。调大 → 滤掉远处小灯条
    double maxArea = 4000.0;  // 轮廓面积上限。调大 → 近处大灯条能进来，但也容易混入大片红色物体

    float minRatio = 2.5f;    // 长宽比下限。调大 → 更"细长"才算灯条（能排除方块，也可能漏掉斜看的灯条）
    float maxRatio = 12.0f;   // 长宽比上限。调小 → 排除细长反光条（比如电线、地板缝）

    float minLength = 10.0f;  // 长边下限（像素）。这是排除"倒影小碎块"最有效的一刀
    float maxLength = 300.0f; // 长边上限（像素）

    //  倾斜度：用长边方向的 tan = |dx| / |dy| 表示。
    //    tan = 0    → 完全竖直
    //    tan = 0.36 → 倾斜约 20°
    //    tan = 0.8  → 倾斜约 38.7°（本项默认上限）
    //  调大 → 允许更歪的灯条（车体侧倾时有用，但会混入斜着的背景线条）
    float maxTanTilt = 0.8f;

    // ======================== 四、两根灯条配成一块装甲板的规则 ========================
    //
    //  为什么需要配对规则？因为画面里往往不止两根"像灯条"的东西：
    //  地面倒影、对面机器人的灯条、反光……都会同时被检出来。
    //  必须有一套规则，从所有候选里挑出"最像同一块装甲板"的一对。
    //
    //  本视频的真实难点：装甲板下面有地板倒影，倒影和灯条颜色一样、形状也像，
    //  只是"更矮、更暗、离得更近"。所以规则要同时看高度、水平和间距。
    // ------------------------------------------------------------------------------

    float maxHeightDiffRatio = 0.35f;   // 两根灯条高度差 / 平均高度，超过就认为不是一对
    float maxCenterYDiffRatio = 0.5f;   // 两根灯条中心的高度差 / 平均高度，超过就排除（排除倒影的关键）
    float minGapRatio = 1.2f;           // 两灯条水平间距 / 平均高度 的下限
    float maxGapRatio = 4.0f;           // 两灯条水平间距 / 平均高度 的上限
    float idealGapRatio = 2.5f;         // "最理想"的间距比例，用于给每一对打分
                                        // 本视频AI实测这个比例是 2.26 ~ 2.71，所以 2.5 很准

    // ======================== 五、装甲板物理尺寸（选做 PnP 用）AI ========================
    //
    //  单位：毫米。这两个数字必须和真实装甲板一致，否则算出来的距离是错的。
    //  下面填的是 RoboMaster 小装甲板的常见外廓尺寸，一定要自己核对！
    //  （量法：灯条外沿到外沿的宽度、灯条上端到下端的高度）
    // ------------------------------------------------------------------------------
    float armorWidthMm  = 135.0f;   // 左右两根灯条外沿之间的水平距离
    float armorHeightMm = 125.0f;   // 单根灯条的长度（上端点到下端点的距离）
};

}   // namespace lb