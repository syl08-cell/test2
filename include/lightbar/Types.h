#pragma once
// ============================================================================
//  Types.h  ——  定义"数据长什么样"
// ----------------------------------------------------------------------------
//  写程序的一个核心思路：先想清楚"我要处理的东西是什么"，再想"怎么处理"。
//  这个文件只做一件事：把"灯条"和"装甲板"这两种东西，用 struct 描述出来。
//
//  什么是 struct（结构体）？
//    它是把几个相关的变量"打包"成一个新类型。
//    比如灯条有"上端点、下端点、长度、宽度"，这四个值永远一起出现，
//    与其到处传 4 个参数，不如打包成一个 LightBar 整体传递。
//
//  为什么数据要单独放一个文件？
//    因为"检测器"和"位姿解算"都要用到这两个类型。
//    如果类型定义写在某个 .cpp 里，另一个 .cpp 就看不见它。
//    放到头文件里，谁需要谁 #include。
// ============================================================================

#include <opencv2/opencv.hpp>   // cv::Point2f、cv::RotatedRect 等类型都在这里
#include <vector>               // std::vector

namespace lb
{

// ----------------------------------------------------------------------------
//  LightBar：一根灯条
//
//  一根灯条在图像里，我们只关心 4 件事：
//    1. 它的上端点在哪（top）
//    2. 它的下端点在哪（bottom）
//    3. 它有多长多宽（length / width，单位像素）
//    4. 它歪不歪（tilt）
//
//  注意：这里存的是"像素坐标"，坐标系是图像坐标系：
//    x 向右为正，y 向下为正，原点在图像左上角。
//    所以"上端点"的 y 值比"下端点"的 y 值小！
// ----------------------------------------------------------------------------
struct LightBar             //一个灯条
{
    cv::Point2f top;        // 上端点（y 较小）
    cv::Point2f bottom;     // 下端点（y 较大）

    float length = 0.0f;    // 长边长度（像素）—— 也就是灯条的"身高"
    float width  = 0.0f;    // 短边长度（像素）—— 灯条的"胖瘦"
    float tilt   = 0.0f;    // 倾斜程度 = |dx| / |dy|，0 表示完全竖直

    // 下面两个是"成员函数"：写在 struct 里面的函数，可以直接用成员变量。
    // 末尾的 const 表示"这个函数不会修改对象本身"（好习惯，能让编译器帮你检查）。

    // 灯条中心点 = 上下端点的中点
    cv::Point2f center() const
    {
        // cv::Point2f 支持加减和乘标量，写起来像向量运算
        return (top + bottom) * 0.5f;
    }
};

// ----------------------------------------------------------------------------
//  ArmorPlate：一块装甲板 = 左灯条 + 右灯条
//
//  比赛规则上，一块装甲板由两根灯条组成。所以"找到一块装甲板"这件事，
//  本质上就是"找到两根配对成功的灯条"。
// ----------------------------------------------------------------------------
struct ArmorPlate           //一对灯条
{
    LightBar left;          // 左边那根
    LightBar right;         // 右边那根
    bool found = false;     // 这一帧到底有没有找到？没找到时 left/right 是无意义的

    // 返回装甲板的 4 个角点，顺序非常重要：
    //   左上 → 右上 → 右下 → 左下
    // 为什么要按这个顺序？因为后面画矩形、做 PnP 都要按顺序连点，
    // 顺序乱了会画出"蝴蝶结"形状，PnP 也会算错。
    std::vector<cv::Point2f> corners() const
    {
        // 花括号初始化列表：依次往 vector 里塞 4 个点
        return { left.top, right.top, right.bottom, left.bottom };
    }

    // 装甲板中心 = 两根灯条中心的中点
    cv::Point2f center() const
    {
        return (left.center() + right.center()) * 0.5f;
    }
};

// ----------------------------------------------------------------------------
//  小工具：把浮点坐标转成整数坐标
//
//  OpenCV 画图函数（cv::line / cv::polylines）要求整数坐标 cv::Point，
//  而我们算出来的是 cv::Point2f（带小数）。所以需要一个转换。
//  cvRound 是"四舍五入到最近的整数"，比直接强制转换 (int) 更准。
// ----------------------------------------------------------------------------
inline cv::Point toPoint(const cv::Point2f& p)
{
    // 图像坐标不会是负数，所以直接 +0.5 再取整就等于四舍五入。
    // （没有用 cvRound 是为了不依赖 OpenCV 的版本差异，写死更省心）
    return cv::Point(static_cast<int>(p.x + 0.5f),
                     static_cast<int>(p.y + 0.5f));
}

}   // namespace lb